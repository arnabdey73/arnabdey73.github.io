const fs = require('fs');
const path = require('path');

// Define categories for CSS files
const cssCategories = {
  layout: [
    'header-footer-fonts.css',
    'site-footer.css',
    'hero-banner.css',
    'intro-card.css',
    'page-title.css',
  ],
  components: [
    'assignment-cards.css',
    'assignment-card-fix.css',
    'blog-feed.css',
    'blog-feed-temp-error.css',
    'blog-note.css',
    'blog-placeholder.css',
    'blog-post-image-fix.css',
    'card-shadows.css',
    'tech-stack.css',
    'tech-stack-mini.css',
  ],
  styles: [
    'typography.css',
    'themes.css',
    'theme-transitions.css',
    'timeline.css',
  ],
  icons: [
    'certification-tech-icons.css',
    'icons-unified.css',
    'mail-icon-fix.css',
    'tech-logos.css',
  ]
};

// Function to concatenate CSS files and convert to SCSS
function processCssCategory(category, files) {
  console.log(`Processing ${category} files...`);
  let concatenated = `// ${category}.scss - Consolidated ${category} styles\n\n`;
  
  // Add comment to indicate this is an auto-generated file
  concatenated += `// This file was automatically generated by the CSS consolidation script\n`;
  concatenated += `// Last updated: ${new Date().toISOString()}\n\n`;
  
  files.forEach(file => {
    const filePath = path.join(__dirname, 'assets', 'css', file);
    
    try {
      if (fs.existsSync(filePath)) {
        let content = fs.readFileSync(filePath, 'utf8');
        
        // Convert CSS to SCSS syntax if needed
        content = content.replace(/\/\*([^*]|[\r\n]|(\*+([^*/]|[\r\n])))*\*+\//g, (match) => {
          // Convert CSS comments to SCSS comments
          return match.split('\n').map(line => line.replace(/\/\*/, '//').replace(/\*\//, '')).join('\n');
        });
        
        concatenated += `// From: ${file}\n${content}\n\n`;
        console.log(`✓ Added ${file}`);
      } else {
        console.log(`⚠ File not found: ${file}`);
      }
    } catch (error) {
      console.error(`Error processing ${file}:`, error);
    }
  });
  
  return concatenated;
}

// Create directories if they don't exist
const mainSassDir = path.join(__dirname, '_sass', 'main');
if (!fs.existsSync(mainSassDir)) {
  fs.mkdirSync(mainSassDir, { recursive: true });
}

// Process each category and save as _sass/main/[category].scss
Object.entries(cssCategories).forEach(([category, files]) => {
  const output = processCssCategory(category, files);
  const outputPath = path.join(__dirname, '_sass', 'main', `_${category}.scss`);
  
  fs.writeFileSync(outputPath, output);
  console.log(`✓ Created ${outputPath}`);
});

// Update the main.scss to import all category files
const mainScss = `// Import all stylesheets 
@import "main/variables";
@import "main/base";
@import "main/layout";
@import "main/components";
@import "main/styles";
@import "main/icons";
`;

fs.writeFileSync(path.join(__dirname, '_sass', 'main.scss'), mainScss);
console.log('✓ Updated main.scss');

console.log('CSS consolidation complete!');
